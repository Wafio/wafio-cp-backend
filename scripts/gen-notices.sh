emit ""
emit "The notices of the npm packages bundled into the dashboard ship with the"
emit "dashboard build and are appended here in the control plane release bundle."
emit ""

mv "$TMP" "$OUT"
rm -f "$TMP.gomods" "$TMP.gopkgs"
echo "Wrote $OUT ($(grep -c '' "$OUT") lines, $(du -h "$OUT" | cut -f1))"
