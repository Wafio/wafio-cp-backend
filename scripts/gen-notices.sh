# Regenerate NOTICES.txt, the third-party attribution of the control plane bundle.
#
# Sections:
#   A. Curated runtime-data attributions (DB-IP, MaxMind, the IP reputation lists,
#      JA3, JA4, the bad-bot list). They are data that the installer and the agents
#      fetch at run time, not Go or npm build dependencies, so they are maintained by
#      hand here. The same text is in wafio-agent-waf (scripts/notices/notices.json):
#      change both.
#   B. The Go standard library and the Go modules compiled into cmd/wafio, each with
#      the verbatim licence text of its module, the NOTICE file of the module when it
#      has one, the licence files that sit inside linked packages, and for the one
#      MPL-2.0 module the place its source is available. The host agent has its own
#      notices (wafio-agent-host) and the Rust WAF agent has its own (wafio-agent-waf).
#   C. Frontend npm packages: the dashboard build brings its own notices, which
#      scripts/release.sh of wafio-release appends to the control plane bundle.
#
# Needs the Go module cache.
#
# Run from the repo root:  ./scripts/gen-notices.sh
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="NOTICES.txt"
TMP="$(mktemp)"
SEP="───────────────────────────────────────────────────────────────────────────────"

emit() { printf '%s\n' "$1" >> "$TMP"; }

