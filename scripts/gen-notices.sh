# ── Section B: Go standard library and Go modules compiled into shipped binaries ──
emit ""
emit "═══════════════════════════════════════════════════════════════════════════════"
emit "SECTION B: GO STANDARD LIBRARY AND GO MODULES (compiled into wafio)"
emit "═══════════════════════════════════════════════════════════════════════════════"
emit ""

goroot="$(go env GOROOT)"
emit "$SEP"
emit "The Go standard library  $(go env GOVERSION)"
emit "https://go.dev"
[ -f "$goroot/LICENSE" ] || { echo "gen-notices: no LICENSE in GOROOT $goroot" >&2; exit 1; }
cat "$goroot/LICENSE" >> "$TMP"
emit ""

go list -deps -f '{{with .Module}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}' \
  ./cmd/wafio 2>/dev/null \
  | sort -u > "$TMP.gomods"

# first_file DIR PATTERN...: the first existing file of DIR that matches one of the names
first_file() {
  local dir=$1 name f
  shift
  for name in "$@"; do
    for f in "$dir"/$name; do
      [ -f "$f" ] && { printf '%s\n' "$f"; return 0; }
    done
  done
  return 1
}

while IFS='|' read -r path ver dir; do
  [ -z "$path" ] && continue
  case "$path" in github.com/wafio/wafio-cp-backend|github.com/wafio/wafio-cp-backend/*) continue ;; esac   # own code, nested modules included
  [ -z "$dir" ] && continue
  licfile="$(first_file "$dir" 'LICENSE*' 'LICENCE*' 'COPYING*' 'License*' 'UNLICENSE*' || true)"
  emit "$SEP"
  emit "$path  $ver"
  if [ -n "$licfile" ]; then
    cat "$licfile" >> "$TMP"
  else
    emit "(no LICENSE file shipped in module; see $path upstream)"
  fi
  # Propagate the NOTICE file of the module when it has one (Apache-2.0 section 4d).
  noticefile="$(first_file "$dir" 'NOTICE' 'NOTICE.txt' 'NOTICE.md' || true)"
  if [ -n "$noticefile" ]; then
    emit ""
    emit "-- NOTICE --"
    cat "$noticefile" >> "$TMP"
  fi
  # MPL-2.0 section 3.2: tell the recipients of the executable where the source is.
  case "$path" in
    github.com/go-sql-driver/mysql)
      emit ""
      emit "-- SOURCE CODE OF THE MPL-2.0 FILES --"
      emit "The files of $path $ver in this product are used unmodified. Their source"
      emit "code is available from https://$path/tree/$ver"
      emit "and from https://proxy.golang.org/$path/@v/$ver.zip."
      ;;
  esac
  emit ""
done < "$TMP.gomods"

# Licence files that sit inside linked packages, below the module root (for example the
# xxhash and snapref code inside klauspost/compress, reuseport inside fasthttp). Text
# identical to the module's own licence file is skipped.
go list -deps -f '{{if .Module}}{{.Module.Path}}|{{.Module.Dir}}|{{.ImportPath}}|{{.Dir}}{{end}}' \
  ./cmd/wafio 2>/dev/null \
  | sort -u > "$TMP.gopkgs"
while IFS='|' read -r mpath mdir ipath pdir; do
  [ -n "$mpath" ] && [ -n "$mdir" ] && [ "$pdir" != "$mdir" ] || continue
  case "$mpath" in github.com/wafio/wafio-cp-backend|github.com/wafio/wafio-cp-backend/*) continue ;; esac
  nested="$(first_file "$pdir" 'LICENSE*' 'LICENCE*' 'COPYING*' 'License*' 'UNLICENSE*' || true)"
  [ -n "$nested" ] || continue
  rootlic="$(first_file "$mdir" 'LICENSE*' 'LICENCE*' 'COPYING*' 'License*' 'UNLICENSE*' || true)"
  if [ -n "$rootlic" ] && cmp -s "$nested" "$rootlic"; then continue; fi
  emit "$SEP"
  emit "$ipath  (licence file inside the package, module $mpath)"
  cat "$nested" >> "$TMP"
  emit ""
done < "$TMP.gopkgs"

# ── Section C: frontend npm packages ─────────────────────────────────────────
emit ""
